#!/usr/bin/env python3
"""Read-only A14m First Light UART witness extraction.

This is an UNTRUSTED log receipt, NOT hardware identity attestation, device
certification, proof of Samsung boot or authorization to flash. The boot image
uses the historical AWG1 kernel and a compile-gated unqualified lab Core.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re

SCHEMA = "prime.mobile.a14m.early-boot-observation.candidate.v0"
PREFIX = "PRIME_A14M_BOOT_OBSERVATION_V0|"
FIELDS = ("source", "model", "compatible_first", "kernel_release",
          "physical_device_qualified")
MAX_UART_BYTES = 4 * 1024 * 1024
MAX_VALUE = 96
VALUE = re.compile(r"^[\x20-\x7e]{1,96}$")
BRIDGE_MARKER = "PRIME_A14M_SOURCE_BRIDGE|not_a_phone_boot_proof=true"
CORE_MARKER = "PRIME_MOB1_CORE_V0|stage=TRANSPORT_ONLY_UNQUALIFIED"


def evaluate(uart: str) -> dict:
    """Parse exactly one bounded, ordered witness and require real Core marker.

    No supplied marker, even if it looks like Samsung hardware, can promote
    device identity, image admission, stock restore or physical boot proof.
    """
    if not isinstance(uart, str):
        raise ValueError("UART_TEXT_REQUIRED")
    if len(uart.encode("utf-8")) > MAX_UART_BYTES:
        raise ValueError("UART_TOO_LARGE")
    lines = uart.splitlines()
    matched = [line[len(PREFIX):] for line in lines if line.startswith(PREFIX)]
    if len(matched) != len(FIELDS):
        raise ValueError("MISSING_OR_DUPLICATE_EARLY_WITNESS")
    values = {}
    for index, text in enumerate(matched):
        field, sep, value = text.partition("=")
        if sep != "=" or field != FIELDS[index] or not VALUE.fullmatch(value):
            raise ValueError("MALFORMED_OR_REORDERED_EARLY_WITNESS")
        values[field] = value
    if values["source"] != "KERNEL_READ_ONLY":
        raise ValueError("SOURCE_NOT_KERNEL_READ_ONLY")
    if values["physical_device_qualified"] != "false":
        raise ValueError("FALSE_HARDWARE_QUALIFICATION")
    if BRIDGE_MARKER not in lines or CORE_MARKER not in lines:
        raise ValueError("CORE_OR_BRIDGE_MARKER_MISSING")

    return {
        "schema": SCHEMA,
        "status": "KERNEL_WITNESS_AND_REAL_CORE_MARKERS_OBSERVED_UNQUALIFIED",
        "source_class": "UNTRUSTED_UART_LOG_NOT_PHYSICAL_ATTESTATION",
        "fields": {key: values[key] for key in ("model", "compatible_first",
                                                "kernel_release")},
        "available_fields": [key for key in ("model", "compatible_first",
                                            "kernel_release")
                             if values[key] != "UNAVAILABLE"],
        "raw_uart_sha256": hashlib.sha256(uart.encode("utf-8")).hexdigest(),
        "real_primed_transport_marker_observed": True,
        "image_booted_on_samsung_proven": False,
        "hardware_identity_qualified": False,
        "boot_chain_qualified": False,
        "recovery_fallback_qualified": False,
        "device_flash_authorized": False,
        "prime_mobile_shell_ready": False,
        "limitations": [
            "The model and compatible values are kernel-projected, not device identity.",
            "The raw UART could be synthetic, replayed or generated by QEMU.",
            "An observed Core marker is not bootc image admission or physical phone boot.",
            "No serial, IMEI, MAC, secrets, partitions or Android properties are read.",
        ],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uart", required=True, type=Path)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if not args.uart.is_file() or args.uart.stat().st_size > MAX_UART_BYTES:
        raise ValueError("UART_FILE_MISSING_OR_OVERSIZED")
    data = args.uart.read_bytes()
    result = evaluate(data.decode("utf-8", errors="replace"))
    payload = json.dumps(result, indent=2, sort_keys=True) + "\n"
    if args.output:
        args.output.write_text(payload, encoding="utf-8")
    else:
        print(payload, end="")


if __name__ == "__main__":
    main()
